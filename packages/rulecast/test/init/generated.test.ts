import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"
import { describe, expect, test, vi } from "vitest"

import { readSourceFile } from "../../src/core/detection/per-rule"
import { allFiles } from "../../src/core/git"
import {
  attributePatternRegex,
  filesOverride,
  findGenerated,
  linguistAttributes,
  readHead,
} from "../../src/init/generated"
import { createRepo } from "../helpers/git"
import { createProject } from "../helpers/project"

const HEY_API = "// This file is auto-generated by @hey-api/openapi-ts\n\nexport const x = 1\n"
const GEN_DEFAULT = "\\.gen\\.[cm]?[jt]sx?$|(^|/)__generated__/"
const genCovered = (file: string) => new RegExp(GEN_DEFAULT).test(file)

/** findGenerated over an in-memory project. */
function find(files: Record<string, string>, covered: ((file: string) => boolean) | null = null) {
  const head = vi.fn(async (file: string) => files[file]?.slice(0, 1024) ?? null)
  const result = findGenerated({
    files: Object.keys(files).sort(),
    readHead: head,
    read: async (file) => files[file] ?? null,
    attributed: async () => [],
    covered,
  })
  return { result, head }
}

/** findGenerated over a git repository written from `files`, with git resolving .gitattributes. */
async function findInRepo(files: Record<string, string>, untracked: Record<string, string> = {}) {
  const root = await createRepo(files)
  for (const [file, text] of Object.entries(untracked)) {
    await mkdir(path.dirname(path.join(root, file)), { recursive: true })
    await writeFile(path.join(root, file), text)
  }
  const all = await allFiles(root)
  return findGenerated({
    files: all,
    readHead: (file) => readHead(root, file),
    read: (file) => readSourceFile(root, file),
    attributed: async (attribute) => (await linguistAttributes(root, all))[attribute],
    covered: null,
  })
}

/** What git says carries linguist-generated when .gitattributes holds only `pattern`. */
async function gitSelects(root: string, pattern: string): Promise<string[]> {
  await writeFile(path.join(root, ".gitattributes"), `${pattern} linguist-generated\n`)
  const files = (await allFiles(root)).filter((file) => file !== ".gitattributes")
  return (await linguistAttributes(root, files))["linguist-generated"]
}

describe("findGenerated", () => {
  test("a dir whose every file has a generator header is offered once, with the header as evidence", async () => {
    const { result } = find({
      "frontend/src/client/index.ts": HEY_API,
      "frontend/src/client/sdk.gen.ts": HEY_API,
      "frontend/src/client/core/auth.gen.ts": HEY_API,
      "frontend/src/main.ts": "export {}\n",
    })
    const { generated } = await result
    expect(generated).toEqual([
      {
        path: "frontend/src/client/",
        kind: "dir",
        files: 3,
        evidence: "header: // This file is auto-generated by @hey-api/openapi-ts",
      },
    ])
  })

  test("the catalog default's files are not read, and still count toward a dir", async () => {
    const { result, head } = find(
      {
        "frontend/src/client/index.ts": HEY_API,
        "frontend/src/client/sdk.gen.ts": "export {}\n",
        "frontend/src/client/core/auth.gen.ts": "export {}\n",
        "frontend/src/main.ts": "export {}\n",
      },
      genCovered,
    )
    expect((await result).generated).toMatchObject([{ path: "frontend/src/client/", files: 3 }])
    expect(head.mock.calls.map(([file]) => file)).toEqual(["frontend/src/client/index.ts", "frontend/src/main.ts"])
  })

  test("a dir mixing marked and hand-written files offers the marked files one by one", async () => {
    const designer = "// <auto-generated />\nusing System;\n"
    const { result } = find({
      "src/Infrastructure/Migrations/20201202_Initial.cs": "public partial class Initial {}\n",
      "src/Infrastructure/Migrations/20201202_Initial.Designer.cs": designer,
      "src/Infrastructure/Migrations/CatalogContextModelSnapshot.cs": designer,
      "src/Infrastructure/Migrations/AddFix.cs": "// hand-written\n",
    })
    expect((await result).generated.map((entry) => [entry.path, entry.kind])).toEqual([
      ["src/Infrastructure/Migrations/20201202_Initial.Designer.cs", "file"],
      ["src/Infrastructure/Migrations/CatalogContextModelSnapshot.cs", "file"],
    ])
  })

  test("paths the catalog default already covers are not offered", async () => {
    const { result } = find(
      { "src/api/a.gen.ts": HEY_API, "src/api/b.gen.ts": HEY_API, "src/x.gen.ts": HEY_API, "src/main.ts": "x\n" },
      genCovered,
    )
    expect((await result).generated).toEqual([])
  })

  test("git decides which files .gitattributes marks; a pattern is offered only when it selects exactly those", async () => {
    const { generated, vendored } = await findInRepo({
      ".gitattributes": [
        "* text=auto",
        "docs/* linguist-generated",
        "**/foo.js linguist-vendored",
        "/api/*.ts linguist-generated",
        "api/keep.ts -linguist-generated",
        "lib/c?.ts linguist-generated",
        "lib/cx.ts !linguist-generated",
        "*.pb.go linguist-generated=true",
        "",
      ].join("\n"),
      "docs/a.md": "a\n",
      "docs/sub/b.md": "b\n",
      "api/client.ts": "x\n",
      "api/keep.ts": "x\n",
      "lib/c1.ts": "x\n",
      "lib/c2.ts": "x\n",
      "lib/cx.ts": "x\n",
      "m.pb.go": "x\n",
      "pb/m.pb.go": "x\n",
      "foo.js": "x\n",
      "src/foo.js": "x\n",
      "src/a/foo.js": "x\n",
      "main.ts": "x\n",
    })
    const evidence = ".gitattributes linguist-generated"
    // `/api/*.ts` and `lib/c?.ts` also select files a later line takes back (-attr, !attr): their
    // files are offered one by one instead.
    expect(generated).toEqual([
      { path: "*.pb.go", kind: "pattern", files: 2, evidence },
      { path: "docs/*", kind: "pattern", files: 1, evidence },
      { path: "api/client.ts", kind: "file", files: 1, evidence },
      { path: "lib/c1.ts", kind: "file", files: 1, evidence },
      { path: "lib/c2.ts", kind: "file", files: 1, evidence },
    ])
    expect(vendored).toEqual([
      { path: "**/foo.js", kind: "pattern", files: 3, evidence: ".gitattributes linguist-vendored" },
    ])
  })

  test("a generated directory that is not committed yet is found through its attribute", async () => {
    const { generated } = await findInRepo(
      { ".gitattributes": "client/** linguist-generated\n", "main.ts": "x\n" },
      { "client/index.ts": "export {}\n", "client/sdk/users.ts": "export {}\n" },
    )
    expect(generated).toEqual([
      { path: "client/**", kind: "pattern", files: 2, evidence: ".gitattributes linguist-generated" },
    ])
  })

  test("the pattern converter selects what git check-attr does", async () => {
    // The reviewer's fixture (tmp/review-24/glob/repo), and the forms named in the review.
    const files = [
      "a/b",
      "a/x/b",
      "a/x/y/b",
      "ab",
      "a/b.ts",
      "api/client.ts",
      "api/keep.ts",
      "api/sub/deep.ts",
      "docs/a.md",
      "docs/sub/b.md",
      "foo.js",
      "gen/x/y.ts",
      "gen/z.ts",
      "lib/c1.ts",
      "lib/c2.ts",
      "lib/cx.ts",
      "m.pb.go",
      "pb/m.pb.go",
      "src/a/b/foo.js",
      "src/a/foo.js",
      "src/a/m.pb.go",
      "src/foo.js",
      "x/a/b.ts",
      "x/b.ts",
      "acb",
      "axb",
    ]
    const root = await createRepo(Object.fromEntries(files.map((file) => [file, "x\n"])))
    // Classes the converter does not take: the pattern is not offered, its files fall back.
    for (const pattern of ["lib/c[]1].ts", "lib/c[!]1].ts", "lib/c[[:digit:]].ts", "a[/]b", "lib/c[1.ts"]) {
      expect(attributePatternRegex(pattern), pattern).toBeNull()
    }
    expect(attributePatternRegex("a[!x]b")).toBe("^(.*/)?a[^/x]b$")
    for (const pattern of [
      "a[!x]b",
      "docs/*",
      "**/foo.js",
      "a/**/b",
      "lib/c[12].ts",
      "lib/c[!1].ts",
      "lib/c?.ts",
      "/api/*.ts",
      "*.pb.go",
      "src/*.js",
      "x/**/b.ts",
      "gen/**",
      "gen/",
      "foo.js",
    ]) {
      const source = attributePatternRegex(pattern)
      const ours = source === null ? [] : files.filter((file) => new RegExp(source).test(file))
      expect(ours, pattern).toEqual(await gitSelects(root, pattern))
    }
  })

  test("vendor/ and third_party/ are offered as vendored and never header-scanned", async () => {
    const { result, head } = find({
      "vendor/github.com/acme/lib/lib.go": "// Code generated by x. DO NOT EDIT.\n",
      "vendor/github.com/acme/lib/util.go": "package lib\n",
      "native/third_party/zlib/inflate.c": "/* DO NOT EDIT */\n",
      "main.go": "package main\n",
    })
    const { generated, vendored } = await result
    expect(vendored).toEqual([
      { path: "native/third_party/", kind: "dir", files: 1, evidence: "third_party/ dir" },
      { path: "vendor/", kind: "dir", files: 2, evidence: "vendor/ dir" },
    ])
    expect(generated).toEqual([])
    expect(head.mock.calls.map(([file]) => file)).toEqual(["main.go"])
  })

  test("vendored dirs the vendored-code default covers are not offered", async () => {
    const vendor = /(^|\/)(vendor|third_party)\//
    const result = await findGenerated({
      files: ["vendor/a.go", "main.go"],
      readHead: async () => null,
      read: async () => null,
      attributed: async () => [],
      covered: null,
      coveredVendored: (file) => vendor.test(file),
    })
    expect(result.vendored).toEqual([])
  })

  test("the project root is never offered, even when every file is marked", async () => {
    const { result } = find({ "a.ts": HEY_API, "b.ts": HEY_API, "lib/c.ts": HEY_API, "lib/d.ts": HEY_API })
    expect((await result).generated.map((entry) => entry.path)).toEqual(["lib/", "a.ts", "b.ts"])
  })

  test("past 20 marked files, the rest are counted, not listed", async () => {
    const files: Record<string, string> = {}
    for (let index = 0; index < 25; index++) {
      files[`src/m${String(index).padStart(2, "0")}.ts`] = HEY_API
      files[`src/h${String(index).padStart(2, "0")}.ts`] = "export {}\n"
    }
    const found = await find(files).result
    expect(found.generated).toHaveLength(20)
    expect(found.notListed).toEqual({ generated: 5, vendored: 0 })
  })

  test("prose is never header-scanned", async () => {
    const { result, head } = find({
      "pkg/i18n/translations/README.md": "# Translations\n\nDo not edit these files: they are generated by Crowdin.\n",
      "pkg/i18n/translations/en.json": "{}\n",
      "main.go": "package main\n",
    })
    expect((await result).generated).toEqual([])
    expect(head.mock.calls.map(([file]) => file)).not.toContain("pkg/i18n/translations/README.md")
  })

  test("an unreadable .gitattributes reads as none", async () => {
    const result = await findGenerated({
      files: ["a.ts", ".gitattributes"],
      readHead: async () => null,
      read: async () => {
        throw new Error("EACCES")
      },
      attributed: async () => {
        throw new Error("git failed")
      },
      covered: null,
    })
    expect(result.generated).toEqual([])
  })

  test("readHead reads at most 1 KB and gives null for binary content", async () => {
    const root = await createProject({ "big.ts": `${"x".repeat(5000)}`, "bin.dat": "ab\0cd" })
    expect((await readHead(root, "big.ts"))?.length).toBe(1024)
    expect(await readHead(root, "bin.dat")).toBeNull()
    expect(await readHead(root, "missing.ts")).toBeNull()
  })
})

describe("filesOverride", () => {
  test("filesOverride anchors dirs and escapes files, keeping the default", () => {
    const paths = [
      { path: "frontend/src/client/", kind: "dir" as const },
      { path: "a/b.ts", kind: "file" as const },
    ]
    expect(filesOverride(GEN_DEFAULT, paths)).toBe(
      "\\.gen\\.[cm]?[jt]sx?$|(^|/)__generated__/|^frontend/src/client/|^a/b\\.ts$",
    )
  })

  test("a dir or file with glob characters stays literal: app/[id]/ is a directory", () => {
    const files = filesOverride("", [
      { path: "app/[id]/", kind: "dir" },
      { path: "a,b{1}.ts", kind: "file" },
    ])
    expect(files).toBe("^app/\\[id\\]/|^a,b\\{1\\}\\.ts$")
    const regex = new RegExp(files)
    expect(regex.test("app/[id]/page.tsx")).toBe(true)
    expect(regex.test("app/i/page.tsx")).toBe(false)
    expect(regex.test("a,b{1}.ts")).toBe(true)
  })

  test("only an entry offered as a pattern becomes the regex it means", () => {
    const files = filesOverride("x", [
      { path: "*.pb.go", kind: "pattern" },
      { path: "api/gen/**", kind: "pattern" },
    ])
    expect(files).toBe("x|^(.*/)?[^/]*\\.pb\\.go$|^api/gen/.*$")
    expect(new RegExp(files).test("rpc/order.pb.go")).toBe(true)
    expect(new RegExp(files).test("rpc/order.go")).toBe(false)
  })
})
