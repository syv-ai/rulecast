import { existsSync } from "node:fs"
import { cp, mkdir, rm, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { dropSelfPointers, rewriteLinks } from "./links"
import {
  AGENT_DOCS_DIR,
  assertPlaced,
  exampleBinding,
  FRAGMENTS,
  INSTALL_SCRIPT,
  PAGES,
  type Page,
  pageParts,
  REPO_ROOT,
  readme,
} from "./sources"

/**
 * Writes the generated pages into src/content/docs, the README fragments into src/generated, and
 * the agent docs, raw and at their repository paths, into public/agents, and install.sh into
 * public/. All gitignored and rewritten by every `dev` and `build`: the source is README.md, guides/, agents/ and install.sh,
 * and a page that only exists after a build is never stale.
 */
const siteDir = fileURLToPath(new URL("../", import.meta.url))
const docsDir = path.join(siteDir, "src/content/docs")
const generatedDir = path.join(siteDir, "src/generated")
const rawAgentDocsDir = path.join(siteDir, "public", AGENT_DOCS_DIR)
export const publicInstaller = path.join(siteDir, "public", INSTALL_SCRIPT)

const HEADER = "<!-- Generated by packages/site/scripts/sync.ts from the repository's Markdown. Do not edit. -->"

function frontmatter(page: Page): string {
  return `---\ntitle: ${JSON.stringify(page.title)}\ndescription: ${JSON.stringify(page.description)}\n---\n`
}

/** A generated page's Markdown body, without pointers to itself, links rewritten: what sync writes after the frontmatter. */
export function pageMarkdown(page: Page, sections: Map<string, string>): string {
  return pageParts(page, sections)
    .map((part) => rewriteLinks(dropSelfPointers(part.markdown, part.source, page.route), part.source))
    .join("\n\n")
}

/** A README fragment's Markdown, links rewritten, as sync writes it to src/generated. */
export function fragmentMarkdown(heading: string, sections: Map<string, string>): string {
  return rewriteLinks(sections.get(heading) ?? "", "README.md")
}

export async function sync(): Promise<string[]> {
  const sections = readme()
  assertPlaced(sections)
  exampleBinding(sections)
  const written: string[] = []
  await rm(generatedDir, { recursive: true, force: true })
  await mkdir(generatedDir, { recursive: true })
  for (const page of PAGES) {
    if ("hand" in page.source) {
      const file = path.join(docsDir, `${page.route}.mdx`)
      if (!existsSync(file)) throw new Error(`hand-written page ${page.route} has no ${path.relative(siteDir, file)}`)
      continue
    }
    const body = pageMarkdown(page, sections)
    const file = path.join(docsDir, `${page.route}.md`)
    await mkdir(path.dirname(file), { recursive: true })
    await writeFile(file, `${frontmatter(page)}\n${HEADER}\n\n${body}\n`)
    written.push(file)
  }
  // A release before plan 28 has no install.sh; the site then serves none.
  const installer = path.join(REPO_ROOT, INSTALL_SCRIPT)
  await rm(publicInstaller, { force: true })
  if (existsSync(installer)) {
    await cp(installer, publicInstaller)
    written.push(publicInstaller)
  }
  await rm(rawAgentDocsDir, { recursive: true, force: true })
  await cp(path.join(REPO_ROOT, AGENT_DOCS_DIR), rawAgentDocsDir, { recursive: true })
  written.push(rawAgentDocsDir)
  for (const [name, heading] of Object.entries(FRAGMENTS)) {
    const file = path.join(generatedDir, `${name}.md`)
    await writeFile(file, `${fragmentMarkdown(heading, sections)}\n`)
    written.push(file)
  }
  return written
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const written = await sync()
  process.stdout.write(`wrote ${written.length} files from README.md and agents/\n`)
}
