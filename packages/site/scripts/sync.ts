import { existsSync, statSync } from "node:fs"
import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { dropSelfPointers, rawAgentDoc, relativeLinks, rewriteLinks } from "./links"
import {
  AGENT_DOCS_DIR,
  assertPlaced,
  exampleBinding,
  FRAGMENTS,
  INSTALL_SCRIPT,
  PAGES,
  type Page,
  pageDescription,
  pageParts,
  REPO_ROOT,
  readme,
} from "./sources"

/**
 * Writes the generated pages into src/content/docs, the README fragments into src/generated, and
 * the agent docs, raw and at their repository paths, into public/agents, and install.sh into
 * public/. All gitignored and rewritten by every `dev` and `build`: the source is README.md, guides/, agents/ and install.sh,
 * and a page that only exists after a build is never stale.
 */
const siteDir = fileURLToPath(new URL("../", import.meta.url))
const docsDir = path.join(siteDir, "src/content/docs")
const generatedDir = path.join(siteDir, "src/generated")
const publicDir = path.join(siteDir, "public")
export const publicInstaller = path.join(publicDir, INSTALL_SCRIPT)

const HEADER = "<!-- Generated by packages/site/scripts/sync.ts from the repository's Markdown. Do not edit. -->"

function frontmatter(page: Page): string {
  return `---\ntitle: ${JSON.stringify(page.title)}\ndescription: ${JSON.stringify(pageDescription(page))}\n---\n`
}

/** A generated page's Markdown body, without pointers to itself, links rewritten: what sync writes after the frontmatter. */
export function pageMarkdown(page: Page, sections: Map<string, string>): string {
  return pageParts(page, sections)
    .map((part) => rewriteLinks(dropSelfPointers(part.markdown, part.source, page.route), part.source))
    .join("\n\n")
}

/** A README fragment's Markdown, links rewritten, as sync writes it to src/generated. */
export function fragmentMarkdown(heading: string, sections: Map<string, string>): string {
  return rewriteLinks(sections.get(heading) ?? "", "README.md")
}

export async function sync(): Promise<string[]> {
  const sections = readme()
  assertPlaced(sections)
  exampleBinding(sections)
  const written: string[] = []
  await rm(generatedDir, { recursive: true, force: true })
  await mkdir(generatedDir, { recursive: true })
  // A page whose source was removed or renamed would otherwise stay on the site, from an earlier sync.
  for (const entry of await readdir(docsDir, { recursive: true })) {
    const file = path.join(docsDir, entry)
    if (entry.endsWith(".md") && (await readFile(file, "utf8")).includes(HEADER)) await rm(file)
  }
  for (const page of PAGES) {
    if ("hand" in page.source) {
      const file = path.join(docsDir, `${page.route}.mdx`)
      if (!existsSync(file)) throw new Error(`hand-written page ${page.route} has no ${path.relative(siteDir, file)}`)
      continue
    }
    const body = pageMarkdown(page, sections)
    const file = path.join(docsDir, `${page.route}.md`)
    await mkdir(path.dirname(file), { recursive: true })
    await writeFile(file, `${frontmatter(page)}\n${HEADER}\n\n${body}\n`)
    written.push(file)
  }
  // A release before plan 28 has no install.sh; the site then serves none.
  const installer = path.join(REPO_ROOT, INSTALL_SCRIPT)
  await rm(publicInstaller, { force: true })
  if (existsSync(installer)) {
    await cp(installer, publicInstaller)
    written.push(publicInstaller)
  }
  written.push(...(await writeRawAgentDocs(publicDir)))
  const unserved = await unservedLinks(publicDir)
  if (unserved.length > 0)
    throw new Error(`raw agent docs link to files the site does not serve:\n${unserved.join("\n")}`)
  for (const [name, heading] of Object.entries(FRAGMENTS)) {
    const file = path.join(generatedDir, `${name}.md`)
    await writeFile(file, `${fragmentMarkdown(heading, sections)}\n`)
    written.push(file)
  }
  return written
}

const isFile = (file: string) => existsSync(file) && statSync(file).isFile()

/**
 * Writes the agent docs, raw and at their repository paths, under `publicDir`: what the site
 * serves raw is agents/ and install.sh. A Markdown file's links to anything else are sent to
 * GitHub (scripts/links.ts, rawAgentDoc).
 */
export async function writeRawAgentDocs(publicDir: string): Promise<string[]> {
  const served = (repoPath: string) =>
    (repoPath.startsWith(`${AGENT_DOCS_DIR}/`) || repoPath === INSTALL_SCRIPT) && isFile(path.join(REPO_ROOT, repoPath))
  const dest = path.join(publicDir, AGENT_DOCS_DIR)
  await rm(dest, { recursive: true, force: true })
  await cp(path.join(REPO_ROOT, AGENT_DOCS_DIR), dest, { recursive: true })
  for (const entry of await readdir(dest, { recursive: true })) {
    if (!entry.endsWith(".md")) continue
    const file = path.join(dest, entry)
    await writeFile(file, rawAgentDoc(await readFile(file, "utf8"), path.posix.join(AGENT_DOCS_DIR, entry), served))
  }
  return [dest]
}

/** Each relative link in the raw agent docs under `publicDir` to a file `publicDir` does not hold. */
export async function unservedLinks(publicDir: string): Promise<string[]> {
  const dest = path.join(publicDir, AGENT_DOCS_DIR)
  const unserved: string[] = []
  for (const entry of await readdir(dest, { recursive: true })) {
    if (!entry.endsWith(".md")) continue
    const file = path.join(dest, entry)
    for (const link of relativeLinks(await readFile(file, "utf8"))) {
      const target = path.resolve(path.dirname(file), decodeURI(link.target.split("#")[0]!))
      if (!isFile(target)) unserved.push(`${AGENT_DOCS_DIR}/${entry}: ${link.target}`)
    }
  }
  return unserved
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const written = await sync()
  process.stdout.write(`wrote ${written.length} files from README.md and agents/\n`)
}
